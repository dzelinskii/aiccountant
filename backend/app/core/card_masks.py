import re

# Последние четыре цифры карты — всё, чем счёт опознаётся в интерфейсе.
CARD_MASK = r"^[0-9]{4}$"

# Счёт с десятком карт — уже нечто иное, чем домашний счёт; ограничение здесь
# затем же, зачем предел числа операций: предсказуемость размера тела запроса.
MAX_CARD_MASKS = 10


def validate_card_masks(masks: list[str]) -> list[str]:
    """Метки карт приходят двумя дорогами — импортом и списком счетов банка, —
    и обе принимают одно и то же: ровно четыре цифры.

    Длиннее — значит, в приложение поехал кусок номера карты, которого мы
    хранить не собирались; короче — метка счёт не опознаёт. И то и другое
    означает баг коллектора, а не опечатку человека.
    """
    for mask in masks:
        if not re.fullmatch(CARD_MASK, mask):
            raise ValueError("метка карты — ровно четыре цифры")
    return masks
