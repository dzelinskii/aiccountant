from decimal import Decimal
from typing import Literal, get_args

# Банконезависимый словарь видов операций. Коннектор каждого банка переводит
# словарь своего банка в этот; бэкенд слов конкретного банка не знает.
OperationKind = Literal[
    "purchase",  # оплата товаров и услуг
    "transfer_person",  # перевод человеку
    "transfer_self",  # между своими счетами
    "cash",  # операции с наличными
    "loan",  # платежи по кредиту
    "income",  # поступление
    "unknown",  # источник не сообщил вид
]

# Тот же словарь значениями — для проверок на входе и перечисления в UI.
# Выводится из Literal, чтобы список не разъезжался с типом.
OPERATION_KINDS: tuple[str, ...] = get_args(OperationKind)

# Не экономические события: деньги лишь меняют место или форму. Из статистики
# и категоризации исключаются. unknown сюда намеренно не входит — неизвестная
# операция должна остаться видимой, а не пропасть молча.
NON_SPENDING_KINDS: tuple[str, ...] = ("transfer_self", "cash")

# Остальные виды — те, что в статистике участвуют. Набор задан белым списком и
# один на обе формы правила: SQL-запрос спрашивает `kind IN`, проверка в Python —
# `kind in`. Чёрный список в одной форме и белый в другой отвечали бы
# противоположное про вид, которого нет в словаре.
IN_STATS_KINDS: tuple[str, ...] = tuple(k for k in OPERATION_KINDS if k not in NON_SPENDING_KINDS)


def counts_in_stats(operation_kind: str, spending_override: bool | None) -> bool:
    """Участвует ли операция в статистике и категоризации.

    Решение человека перекрывает вид операции в обе стороны; null означает, что
    решения не было и судит вид.

    Здесь правило живёт целиком и в единственном экземпляре: и SQL-запросы
    статистики, и ответ API отвечают на вопрос через эту функцию. Вторая
    реализация развела бы цифры дашборда с тем, что человек видит в строке.
    """
    if spending_override is not None:
        return spending_override
    return operation_kind in IN_STATS_KINDS


def kind_from_amount(amount: Decimal) -> OperationKind:
    """Вид там, где источник знает только знак суммы: ручной ввод и регулярные
    правила. Банк присылает вид сам, и через эту функцию не проходит."""
    return "purchase" if amount < 0 else "income"
