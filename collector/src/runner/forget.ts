import { BANK_NAMES } from '../plugins/registry'
import { forgetProfile } from './browser'
import { osSecretStore } from './secret-store'

// Отдельная команда, а не совет «удалите каталог руками»: забыть доступ к
// банку — часть модели безопасности, и делать это должен сам коллектор,
// который знает, где лежит профиль и где лежит секрет. Банков несколько, и
// «забыть» должно затрагивать все сразу, а не только тот, с которым
// работали последним.
//
// Секрет живёт не только в профиле браузера: у Сбербанка нужные куки
// сессионные и в профиле не остаются, поэтому секрет хранится ещё и в
// хранилище ОС (secret-store.ts). Стирать нужно оба места — иначе команда
// солжёт: скажет, что доступа больше нет, а секрет останется в хранилище.
//
// Отсутствие профиля или записи в хранилище ошибкой не считается: забыть
// доступ должно получаться и до первого входа, и повторно.
const secretStore = osSecretStore()
for (const bank of BANK_NAMES) {
  await forgetProfile(bank)
  await secretStore.clear(bank)
}

// «больше нет», а не «удалён»: команда отрабатывает и на пустом месте, и
// сообщать о несделанном удалении незачем — важен итог
console.log(`Доступ забыт: ${BANK_NAMES.join(', ')}.`)
console.log('Следующий сбор откроет окно входа заново.')
