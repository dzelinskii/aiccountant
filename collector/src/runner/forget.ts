import { BANK_NAMES } from '../plugins/registry'
import { forgetProfile } from './browser'

// Отдельная команда, а не совет «удалите каталог руками»: забыть доступ к
// банку — часть модели безопасности, и делать это должен сам коллектор,
// который знает, где лежит профиль. Профилей несколько — по одному на банк, —
// и «забыть» должно затрагивать все сразу, а не только тот, с которым
// работали последним.
//
// Отсутствие профиля ошибкой не считается: забыть доступ должно получаться и
// до первого входа, и повторно.
for (const bank of BANK_NAMES) {
  await forgetProfile(bank)
}

// «больше нет», а не «удалён»: команда отрабатывает и на пустом месте, и
// сообщать о несделанном удалении незачем — важен итог
console.log(`Доступ забыт: ${BANK_NAMES.join(', ')}.`)
console.log('Следующий сбор откроет окно входа заново.')
